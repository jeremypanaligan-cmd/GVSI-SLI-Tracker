-- ============================================================================
-- hardening_advisor_fixes — found by the Supabase security advisors, not by code
-- review. Two default grants in Supabase made more public than intended:
--
--   1. New views in `public` inherit SELECT for anon/authenticated, so
--      `sli_active_users` returned the live roster to anyone holding the (public)
--      anon key. Confirmed with a real request, then closed.
--   2. `revoke ... from anon` is not enough for a function: every role is a member of
--      PUBLIC, which holds the default EXECUTE grant. `sli_is_developer` therefore
--      stayed callable and had to be revoked FROM PUBLIC.
--
-- The advisor reports RLS-enabled-no-policy on all five tables as INFO. That is the
-- intended state: no policy means nothing is publicly readable, and all app access
-- goes through the functions above.
-- ============================================================================

revoke all on public.sli_active_users from anon, authenticated;
alter view public.sli_active_users set (security_invoker = true);

revoke execute on function public.sli_is_developer(uuid) from public, anon, authenticated;

-- ============================================================================
-- archive_public_read — the app reads CLOSED months directly from Supabase
--
-- Unlike everything above, these two tables have to be readable WITHOUT a session: the
-- browser holds only the public anon key, and a closed month is fetched from here
-- instead of from the spreadsheet.
--
-- The `revoke all ... from anon` earlier in this file was the right call for the access
-- tables and the wrong one for the archive — it broke archived months in the app (401
-- on every read, silently falling back to sheet-only) until this was applied. It is
-- recorded here so that re-running this file on a fresh project cannot repeat that.
--
-- Read only. INSERT/UPDATE/DELETE stay service_role-only, which is what stops a
-- browser-side bug from corrupting a closed month, and what the Apps Script's
-- 'Test Supabase Connection' verifies before the archive job is switched on.
-- ============================================================================

grant select on public.sli_raw_daily to anon, authenticated;
grant select on public.sli_mtd       to anon, authenticated;

drop policy if exists sli_raw_daily_read on public.sli_raw_daily;
create policy sli_raw_daily_read on public.sli_raw_daily
  for select to anon, authenticated using (true);

drop policy if exists sli_mtd_read on public.sli_mtd;
create policy sli_mtd_read on public.sli_mtd
  for select to anon, authenticated using (true);
