-- Two jobs live here:
--
--   1. COLD ARCHIVE  — closed months move out of the Google Sheet into
--      `sli_raw_daily` + `sli_mtd`, so the spreadsheet stops growing forever.
--      Written by the Apps Script archive job with the service_role key.
--
--   2. ACCESS        — `sli_users`/`sli_sessions`/`sli_settings` replace the publicly
--      readable Login Credentials sheet, and give the app session tokens, presence and
--      the maintenance switch.
--
-- Access model: the app is a static site holding only the PUBLIC anon key, so every
-- table has RLS on with NO anonymous policy. All reads and writes go through
-- SECURITY DEFINER functions; the privileged ones check the caller's session token
-- inside Postgres (the token IS the credential — the browser cannot assert a role).
-- ============================================================================

-- ---------------------------------------------------------------- raw daily --
create table if not exists public.sli_raw_daily (
  id bigint generated by default as identity primary key,
  plan text not null,                   -- 'fiberx' | 'bida' | 'sme'
  month_key text not null,              -- '2026-09'
  report_date date not null,
  date_label text not null,             -- 'September 1, 2026' — the app's date key
  area text not null,
  is_overall_total boolean not null default false,
  bf numeric, inc numeric, total_jo numeric,
  comp_from_total numeric, comp_from_rjo numeric, total_completed numeric,
  rjo_incoming numeric, rjo_redispatched numeric, total_rjo numeric,
  carry_over numeric, mtd numeric, gross numeric, net numeric, target numeric,
  pct text,                             -- text: preserves '#DIV/0!' verbatim
  -- gross / net are SME's MRC collection (the sheet's L and M). BIDA and FIBERX have no
  -- such columns, so their rows store NULL rather than a zero that would read as a figure
  -- nobody collected. `target` is a peso figure on SME and a ticket count elsewhere.
  row_order integer,
  archived_at timestamptz not null default now(),
  constraint sli_raw_daily_key unique (plan, report_date, area)
);
create index if not exists sli_raw_daily_plan_month_idx on public.sli_raw_daily (plan, month_key);

-- -------------------------------------------------------------------- mtd ----
create table if not exists public.sli_mtd (
  id bigint generated by default as identity primary key,
  plan text not null,
  month_key text not null,
  month_label text not null,            -- 'September 2026'
  area text not null,
  is_overall_total boolean not null default false,
  comp_from_total numeric, comp_from_rjo numeric, total_completed numeric,
  this_mo_rjo numeric, prev_mos_rjo numeric, total_rjo numeric,
  last_mtd numeric, gross numeric, net numeric, target numeric, total_incoming numeric,
  -- gross / net: SME only, same as sli_raw_daily. NULL on BIDA and FIBERX.
  last_pct text,
  row_order integer,
  archived_at timestamptz not null default now(),
  constraint sli_mtd_key unique (plan, month_key, area)
);
create index if not exists sli_mtd_plan_month_idx on public.sli_mtd (plan, month_key);
create index if not exists sli_mtd_plan_total_idx on public.sli_mtd (plan, is_overall_total);

-- The `OVER ALL TOTAL` row is archived VERBATIM, never recomputed: it is not always
-- the sum of the area rows (BIDA August: total 387 vs area sum 370), and it is the
-- number the dashboard showed when that month was live.

-- ------------------------------------------------------------------ users ----
create table if not exists public.sli_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,          -- lowercase SHA-256 hex (unchanged scheme)
  full_name text,
  role text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- --------------------------------------------------------------- sessions ----
create table if not exists public.sli_sessions (
  token uuid primary key default gen_random_uuid(),
  username text not null,
  full_name text,
  role text,
  plan text,
  view text,
  user_agent text,
  started_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  ended_at timestamptz,
  revoked_at timestamptz
);
create index if not exists sli_sessions_last_seen_idx on public.sli_sessions (last_seen_at desc);
create index if not exists sli_sessions_username_idx on public.sli_sessions (username);

-- --------------------------------------------------------------- settings ----
create table if not exists public.sli_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by text
);

