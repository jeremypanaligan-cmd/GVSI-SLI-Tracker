-- No policies on purpose for these three: nothing here is publicly readable. A request
-- with the anon key gets 401 "permission denied for table sli_users".
--
-- The two ARCHIVE tables are the exception, applied at the end of this file: the app
-- reads closed months straight from Supabase with the public anon key, so they carry a
-- SELECT-only read policy while every write still requires service_role.
revoke all on public.sli_raw_daily from anon, authenticated;
revoke all on public.sli_mtd       from anon, authenticated;
revoke all on public.sli_users     from anon, authenticated;
revoke all on public.sli_sessions  from anon, authenticated;
revoke all on public.sli_settings  from anon, authenticated;

grant all on public.sli_raw_daily to service_role;
grant all on public.sli_mtd       to service_role;
grant all on public.sli_users     to service_role;
grant all on public.sli_sessions  to service_role;
grant all on public.sli_settings  to service_role;

-- ------------------------------------------------------------------- view ----
create or replace view public.sli_active_users as
select token, username, full_name, role, plan, view, started_at, last_seen_at,
       extract(epoch from (now() - started_at))::bigint as active_seconds
from public.sli_sessions
where ended_at is null
  and revoked_at is null
  and last_seen_at > now() - interval '2 minutes';

-- ============================================================== functions ====

create or replace function public.sli_is_developer(p_token uuid)
returns boolean
language sql security definer set search_path = public, pg_temp as $$
  select exists (
    select 1 from public.sli_sessions s
    where s.token = p_token
      and s.ended_at is null
      and s.revoked_at is null
      and lower(trim(coalesce(s.role, ''))) = 'developer'
  );
$$;

-- ------------------------------------------------------------------ login ----
-- Empty result = wrong credentials. A match opens a session row and returns its token.
create or replace function public.verify_login(p_username text, p_hash text, p_user_agent text default null)
returns table (token uuid, username text, full_name text, role text)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_user public.sli_users%rowtype;
  v_token uuid;
begin
  select * into v_user from public.sli_users u
  where lower(trim(u.username)) = lower(trim(coalesce(p_username, '')))
    and u.password_hash = lower(trim(coalesce(p_hash, '')))
    and u.is_active
  limit 1;

  if not found then
    return;
  end if;

  insert into public.sli_sessions (username, full_name, role, user_agent)
  values (v_user.username, v_user.full_name, v_user.role, p_user_agent)
  returning sli_sessions.token into v_token;

  return query select v_token, v_user.username, v_user.full_name, v_user.role;
end;
$$;

-- ---------------------------------------------------------------- presence ----
-- One call per heartbeat: records presence, answers "is my token still valid?" and
-- hands back the maintenance state.
create or replace function public.presence_ping(p_token uuid, p_plan text default null, p_view text default null)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_session public.sli_sessions%rowtype;
  v_maintenance jsonb;
  v_valid boolean := false;
  v_user public.sli_users%rowtype;
begin
  select * into v_session from public.sli_sessions s where s.token = p_token;

  if found and v_session.ended_at is null and v_session.revoked_at is null then
    -- A user deactivated mid-session is treated as revoked.
    select * into v_user from public.sli_users u where lower(u.username) = lower(v_session.username);
    if found and v_user.is_active then
      v_valid := true;
      update public.sli_sessions s
         set last_seen_at = now(),
             plan = coalesce(p_plan, s.plan),
             view = coalesce(p_view, s.view)
       where s.token = p_token;
    else
      update public.sli_sessions s set revoked_at = coalesce(s.revoked_at, now()) where s.token = p_token;
    end if;
  end if;

  v_maintenance := public.maintenance_get();

  return jsonb_build_object('token_valid', v_valid, 'maintenance', v_maintenance);
end;
$$;

create or replace function public.presence_leave(p_token uuid)
returns void
language sql security definer set search_path = public, pg_temp as $$
  update public.sli_sessions s
     set ended_at = coalesce(s.ended_at, now())
   where s.token = p_token;
$$;

-- ------------------------------------------------------------- maintenance ----
-- Public: the login screen and every signed-out visitor needs this. An expired flag
-- reads as disabled, so a forgotten switch can never lock the team out.
create or replace function public.maintenance_get()
returns jsonb
language sql security definer set search_path = public, pg_temp as $$
  select coalesce(
    (select case
       when (s.value->>'enabled')::boolean is not true then
         jsonb_build_object('enabled', false)
       when s.value ? 'expires_at'
         and (s.value->>'expires_at') <> ''
         and (s.value->>'expires_at')::timestamptz <= now() then
         jsonb_build_object('enabled', false, 'expired', true,
                            'since', s.value->'since', 'by', s.value->'by')
       else
         jsonb_build_object('enabled', true,
                            'message', s.value->'message',
                            'since', s.value->'since',
                            'by', s.value->'by',
                            'expires_at', s.value->'expires_at')
     end
     from public.sli_settings s where s.key = 'maintenance'),
    jsonb_build_object('enabled', false)
  );
$$;

create or replace function public.maintenance_set(p_token uuid, p_enabled boolean,
                                                 p_message text default null,
                                                 p_expires_at timestamptz default null)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_row public.sli_sessions%rowtype;
  v_on boolean := coalesce(p_enabled, false);
  v_existing jsonb;
begin
  if not public.sli_is_developer(p_token) then
    raise exception 'not authorized: developer session required' using errcode = '42501';
  end if;

  select * into v_row from public.sli_sessions s where s.token = p_token;
  select value into v_existing from public.sli_settings where key = 'maintenance';

  -- jsonb_build_object() stores a SQL NULL as a JSON null, and `value->'since'` then
  -- returns that JSON null (NOT SQL NULL), so a plain coalesce() would keep the empty
  -- value forever after the first off-transition — the panel would read "Ni — noong —"
  -- and nobody would know who locked the app. Reuse a stored value only when it is an
  -- actual string; otherwise stamp a fresh one.
  insert into public.sli_settings (key, value, updated_at, updated_by)
  values ('maintenance', jsonb_build_object(
            'enabled', v_on,
            'message', nullif(trim(coalesce(p_message, '')), ''),
            'expires_at', case when v_on then p_expires_at else null end,
            'since', case when v_on then to_jsonb(now()) else null end,
            'by', case when v_on then to_jsonb(v_row.username) else null end
          ), now(), v_row.username)
  on conflict (key) do update
     set value = jsonb_build_object(
           'enabled', v_on,
           'message', nullif(trim(coalesce(p_message, '')), ''),
           'expires_at', case when v_on then p_expires_at else null end,
           -- "since"/"by" stay sticky while the switch is on, so editing the message
           -- does not erase who turned it on.
           'since', case when v_on and jsonb_typeof(v_existing->'since') = 'string'
                         then v_existing->'since'
                         when v_on then to_jsonb(now()) else null end,
           'by', case when v_on and jsonb_typeof(v_existing->'by') = 'string'
                      then v_existing->'by'
                      when v_on then to_jsonb(v_row.username) else null end
         ),
         updated_at = now(),
         updated_by = v_row.username;

  return public.maintenance_get();
end;
$$;

-- ------------------------------------------------------------------- admin ----
create or replace function public.active_users(p_token uuid)
returns table (username text, full_name text, role text, plan text, view text,
               started_at timestamptz, last_seen_at timestamptz, active_seconds bigint)
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not public.sli_is_developer(p_token) then
    raise exception 'not authorized: developer session required' using errcode = '42501';
  end if;

  return query
    select a.username, a.full_name, a.role, a.plan, a.view,
           a.started_at, a.last_seen_at, a.active_seconds
    from public.sli_active_users a
    order by a.started_at asc;
end;
$$;

create or replace function public.recent_sessions(p_token uuid, p_limit integer default 25)
returns table (username text, full_name text, role text, started_at timestamptz,
               last_seen_at timestamptz, ended_at timestamptz, revoked_at timestamptz,
               duration_seconds bigint)
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not public.sli_is_developer(p_token) then
    raise exception 'not authorized: developer session required' using errcode = '42501';
  end if;

  return query
    select s.username, s.full_name, s.role, s.started_at, s.last_seen_at,
           s.ended_at, s.revoked_at,
           extract(epoch from (coalesce(s.ended_at, s.last_seen_at) - s.started_at))::bigint
    from public.sli_sessions s
    order by s.started_at desc
    limit greatest(1, least(coalesce(p_limit, 25), 200));
end;
$$;

create or replace function public.force_signout_all(p_token uuid, p_keep_self boolean default true)
returns integer
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_count integer;
begin
  if not public.sli_is_developer(p_token) then
    raise exception 'not authorized: developer session required' using errcode = '42501';
  end if;

  update public.sli_sessions s
     set revoked_at = now()
   where s.revoked_at is null
     and s.ended_at is null
     and (not coalesce(p_keep_self, true) or s.token <> p_token);

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

